package nl.patropia.maven.plugin;

import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.Node;
import org.w3c.dom.NodeList;

import javax.xml.parsers.DocumentBuilder;
import javax.xml.parsers.DocumentBuilderFactory;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assertions.fail;

/**
 * Guards the {@code sbomAggregator.*} user property naming convention of every goal.
 * <p>
 * The {@code @Parameter} annotation of the Maven Plugin API is retained at {@code CLASS} level and can therefore not
 * be read through reflection. This test reads the plugin descriptor generated by {@code maven-plugin-plugin}
 * ({@code META-INF/maven/plugin.xml}, available on the test classpath because {@code process-classes} runs before
 * {@code test}) and verifies the effective property wiring Maven performs for the {@code aggregate-sboms} and
 * {@code diff-sboms} goals.
 * </p>
 * <p>
 * {@code aggregate-sboms} parameters expose {@code sbomAggregator.<name>}. {@code diff-sboms} parameters expose
 * {@code sbomAggregator.diff.<name>}, except for the parameters it shares with {@code aggregate-sboms}
 * ({@code outputName}, {@code outputExtension} and {@code maxSbomSize}), which must bind the very same property in
 * both goals. Read-only parameters (such as the {@code diff-sboms} {@code buildDirectory}) are supplied by Maven and
 * must not be bound to a user property at all.
 * </p>
 */
class ParameterPropertyNamingTest {

    private static final String GOAL = "aggregate-sboms";
    private static final String DIFF_GOAL = "diff-sboms";
    private static final String PREFIX = "sbomAggregator.";
    private static final String DIFF_PREFIX = PREFIX + "diff.";

    /** Every configurable (editable) parameter of the aggregate goal, with the user property it must expose. */
    private static final Set<String> EXPECTED_PARAMETERS = new TreeSet<>(List.of(
            "projectSbom",
            "scanSboms",
            "outputDirectory",
            "outputName",
            "outputClassifier",
            "outputExtension",
            "specVersion",
            "outputTimestamp",
            "dependencyClassifiers",
            "dependencyExtensions",
            "includeTransitive",
            "includeVulnerabilities",
            "includeScopes",
            "excludes",
            "failOnMissingSbom",
            "maxSbomSize",
            "failOnInvalidSbom",
            "validateOutput",
            "attach",
            "generateSpdx",
            "skip"));

    /** Every configurable (editable) parameter of the diff goal; the property is {@code sbomAggregator.diff.<name>}. */
    private static final Set<String> DIFF_EXPECTED_PARAMETERS = new TreeSet<>(List.of(
            "baseline",
            "current",
            "outputName",
            "outputExtension",
            "reportFormats",
            "outputDirectory",
            "failOnNewVulnerabilities",
            "skip",
            "maxSbomSize"));

    /**
     * Parameters of {@code diff-sboms} that deliberately reuse an {@code aggregate-sboms} user property, so a single
     * {@code -DsbomAggregator.*} flag configures both goals. The value is the property the descriptor must bind.
     */
    private static final Map<String, String> DIFF_SHARED_PROPERTIES = new TreeMap<>();

    static {
        DIFF_SHARED_PROPERTIES.put("maxSbomSize", PREFIX + "maxSbomSize");
        DIFF_SHARED_PROPERTIES.put("outputExtension", PREFIX + "outputExtension");
        DIFF_SHARED_PROPERTIES.put("outputName", PREFIX + "outputName");
    }

    private static Element mojo;
    private static Element diffMojo;

    @BeforeAll
    static void loadDescriptor() throws Exception {
        DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
        // The descriptor is generated locally; reject any DTD/entity processing.
        factory.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true);
        factory.setExpandEntityReferences(false);
        DocumentBuilder builder = factory.newDocumentBuilder();
        try (InputStream in = ParameterPropertyNamingTest.class.getClassLoader()
                .getResourceAsStream("META-INF/maven/plugin.xml")) {
            assertNotNull(in, "META-INF/maven/plugin.xml is missing from the classpath - run 'mvn test' "
                    + "(the plugin descriptor is generated in the process-classes phase)");
            Document descriptor = builder.parse(in);
            mojo = findMojo(descriptor, GOAL);
            diffMojo = findMojo(descriptor, DIFF_GOAL);
        }
        assertNotNull(mojo, "No <mojo> with goal '" + GOAL + "' found in the plugin descriptor");
        assertNotNull(diffMojo, "No <mojo> with goal '" + DIFF_GOAL + "' found in the plugin descriptor");
    }

    @Test
    void everyEditableParameterExposesAPrefixedUserProperty() {
        assertEveryEditableParameterExposesItsProperty(mojo, GOAL, PREFIX, EXPECTED_PARAMETERS,
                Map.of(), "'" + PREFIX + "*'");
    }

    @Test
    void everyDiffEditableParameterExposesAPrefixedUserProperty() {
        assertEveryEditableParameterExposesItsProperty(diffMojo, DIFF_GOAL, DIFF_PREFIX, DIFF_EXPECTED_PARAMETERS,
                DIFF_SHARED_PROPERTIES, "'" + DIFF_PREFIX + "*' (or a shared '" + PREFIX + "*' property)");
    }

    @Test
    void noBareUserPropertyIsWired() {
        assertNoBareUserPropertyIsWired(mojo, GOAL);
        assertNoBareUserPropertyIsWired(diffMojo, DIFF_GOAL);
    }

    @Test
    void legacyBarePropertyNamesAreNoLongerHonoured() throws Exception {
        Element configuration = firstChild(mojo, "configuration");
        assertNotNull(configuration);

        // The plugin reads no system/user properties itself, so a bare -DspecVersion=... cannot influence
        // the build: only the descriptor expression below is bound by Maven.
        Element specVersion = firstChild(configuration, "specVersion");
        assertNotNull(specVersion);
        assertEquals("${" + PREFIX + "specVersion}", specVersion.getTextContent().trim(),
                "specVersion must be bound to -DsbomAggregator.specVersion (bare -DspecVersion is not supported)");
        assertEquals("1.7", specVersion.getAttribute("default-value"),
                "The documented default spec version changed; keep README/CHANGELOG in sync");
        // Ties the documented default to the code path: whatever the descriptor declares must be a
        // supported spec version, and today that is the CycloneDX 1.7 schema version.
        assertEquals(org.cyclonedx.Version.VERSION_17,
                SpecValidation.toCycloneDxVersion(specVersion.getAttribute("default-value")),
                "the default specVersion must map to the CycloneDX 1.7 schema version");
    }

    @Test
    void everyEditableParameterIsDocumentedWithItsUserProperty() throws Exception {
        assertEveryParameterIsDocumented(mojo, GOAL, PREFIX, Map.of());
    }

    @Test
    void everyDiffEditableParameterIsDocumentedWithItsUserProperty() throws Exception {
        assertEveryParameterIsDocumented(diffMojo, DIFF_GOAL, DIFF_PREFIX, DIFF_SHARED_PROPERTIES);
    }

    @Test
    void readmeDoesNotAdvertiseDeprecatedBarePropertyNames() throws Exception {
        String readme = read("README.md");
        assertTrue(readme.contains("sbomAggregator.specVersion"),
                "README.md must document the sbomAggregator.* user properties");
        assertTrue(!readme.contains("-DspecVersion=") && !readme.contains("-DprojectSbom="),
                "README.md must not advertise deprecated bare -D property names");
    }

    @Test
    void readmeDocumentsThatDiffCurrentDefaultsToTheBuildDirectory() throws Exception {
        String readme = read("README.md");
        assertTrue(readme.contains("sbomAggregator.diff.current"),
                "README.md must document sbomAggregator.diff.current");
        assertTrue(readme.contains("${project.build.directory}/<outputName>.<outputExtension>"),
                "README.md must document that diff-sboms reads the current SBOM from "
                        + "${project.build.directory}/<outputName>.<outputExtension> by default");
        assertTrue(readme.contains("does **not** follow a custom `sbomAggregator.outputDirectory`"),
                "README.md must warn that a custom sbomAggregator.outputDirectory is not used by diff-sboms "
                        + "(the current SBOM is read from the build directory)");
    }

    @Test
    void diffGoalReusesTheSharedOutputNameAndExtensionProperties() {
        Element aggregateConfiguration = firstChild(mojo, "configuration");
        Element diffConfiguration = firstChild(diffMojo, "configuration");
        assertNotNull(aggregateConfiguration);
        assertNotNull(diffConfiguration);

        for (Map.Entry<String, String> shared : DIFF_SHARED_PROPERTIES.entrySet()) {
            String name = shared.getKey();
            Element aggregate = firstChild(aggregateConfiguration, name);
            Element diff = firstChild(diffConfiguration, name);
            assertNotNull(aggregate, GOAL + " has no <" + name + "> parameter");
            assertNotNull(diff, DIFF_GOAL + " has no <" + name + "> parameter");
            assertEquals("${" + shared.getValue() + "}", aggregate.getTextContent().trim(),
                    name + " of " + GOAL + " must be bound to " + shared.getValue());
            assertEquals(aggregate.getTextContent().trim(), diff.getTextContent().trim(),
                    name + " must be bound to the same user property in " + GOAL + " and " + DIFF_GOAL);
        }

        // The diff report directory is deliberately separate from the directory of the aggregated SBOM.
        Element diffOutputDirectory = firstChild(diffConfiguration, "outputDirectory");
        assertNotNull(diffOutputDirectory);
        assertEquals("${" + DIFF_PREFIX + "outputDirectory}", diffOutputDirectory.getTextContent().trim(),
                "the diff report directory must stay on its own " + DIFF_PREFIX + "outputDirectory property");
    }

    @Test
    void diffBuildDirectoryIsReadOnlyAndNotUserConfigurable() {
        Element configuration = firstChild(diffMojo, "configuration");
        assertNotNull(configuration);

        assertTrue(!editableParameterNames(diffMojo, DIFF_GOAL).contains("buildDirectory"),
                "buildDirectory must stay a read-only parameter: Maven supplies ${project.build.directory}");

        Element buildDirectory = firstChild(configuration, "buildDirectory");
        assertNotNull(buildDirectory, DIFF_GOAL + " must bind buildDirectory to locate the aggregated SBOM");
        assertEquals("", buildDirectory.getTextContent().trim(),
                "a read-only parameter must not be bound to a user property");
        assertEquals("${project.build.directory}", buildDirectory.getAttribute("default-value"),
                "buildDirectory must default to ${project.build.directory}");
    }

    // ------------------------------------------------------------------------------- assertions

    private static void assertEveryEditableParameterExposesItsProperty(Element goalElement, String goal,
            String defaultPrefix, Set<String> expectedParameters, Map<String, String> sharedProperties,
            String allowedProperties) {
        Element configuration = firstChild(goalElement, "configuration");
        assertNotNull(configuration, "The descriptor has no <configuration> section for goal " + goal);

        Set<String> editable = editableParameterNames(goalElement, goal);
        assertEquals(expectedParameters, new TreeSet<>(editable),
                "The set of configurable parameters of " + goal + " changed; update this test and the README "
                        + "when adding/removing one");

        List<String> problems = new ArrayList<>();
        for (String name : editable) {
            Element element = firstChild(configuration, name);
            if (element == null) {
                problems.add(name + ": no <" + name + "> entry in <configuration>");
                continue;
            }
            String expression = element.getTextContent().trim();
            String expected = "${" + propertyFor(name, defaultPrefix, sharedProperties) + "}";
            if (!expected.equals(expression)) {
                problems.add(name + ": expected user property " + expected + " but the descriptor binds '"
                        + expression + "'");
            }
        }
        assertTrue(problems.isEmpty(),
                "Every parameter of " + goal + " must expose a " + allowedProperties + " user property:"
                        + System.lineSeparator() + String.join(System.lineSeparator(), problems));
    }

    private static void assertNoBareUserPropertyIsWired(Element goalElement, String goal) {
        Element configuration = firstChild(goalElement, "configuration");
        assertNotNull(configuration, "The descriptor has no <configuration> section for goal " + goal);

        List<String> bare = new ArrayList<>();
        for (Element element : childElements(configuration)) {
            String expression = element.getTextContent().trim();
            if (!expression.startsWith("${") || !expression.endsWith("}")) {
                continue;
            }
            String property = expression.substring(2, expression.length() - 1);
            if (!property.startsWith(PREFIX)) {
                bare.add(element.getTagName() + " -> " + expression);
            }
        }
        assertTrue(bare.isEmpty(),
                "Only 'sbomAggregator.*' user properties are supported; found unprefixed expressions in " + goal
                        + ":" + System.lineSeparator() + String.join(System.lineSeparator(), bare));
    }

    private static void assertEveryParameterIsDocumented(Element goalElement, String goal, String defaultPrefix,
            Map<String, String> sharedProperties) throws Exception {
        String readme = read("README.md");
        Element configuration = firstChild(goalElement, "configuration");
        assertNotNull(configuration, "The descriptor has no <configuration> section for goal " + goal);

        List<String> undocumented = new ArrayList<>();
        for (String name : editableParameterNames(goalElement, goal)) {
            String row = "`" + name + "` | `" + propertyFor(name, defaultPrefix, sharedProperties) + "`";
            // Parameters that exist in both goals are documented with the goal in brackets, e.g.
            // "| `outputDirectory` (diff-sboms) | `sbomAggregator.diff.outputDirectory` | ..."
            String qualifiedRow = "`" + name + "` (" + goal + ") | `"
                    + propertyFor(name, defaultPrefix, sharedProperties) + "`";
            if (!readme.contains(row) && !readme.contains(qualifiedRow)) {
                undocumented.add(name + " -> " + propertyFor(name, defaultPrefix, sharedProperties));
            }
        }
        assertTrue(undocumented.isEmpty(),
                "README.md parameter table must document each parameter of " + goal + " together with its user "
                        + "property (expected a row starting with '`<name>` | `sbomAggregator.<name>`' or "
                        + "'`<name>` (" + goal + ") | `sbomAggregator...`'): " + undocumented);
    }

    private static String propertyFor(String name, String defaultPrefix, Map<String, String> sharedProperties) {
        String shared = sharedProperties.get(name);
        return shared != null ? shared : defaultPrefix + name;
    }

    /**
     * Reads a documentation file from the project base directory (the Maven working directory during tests).
     */
    private static String read(String relativePath) throws Exception {
        java.io.File file = new java.io.File(relativePath);
        if (!file.isFile()) {
            file = new java.io.File(System.getProperty("basedir", "."), relativePath);
        }
        assertTrue(file.isFile(), relativePath + " not found - the tests must run from the project base directory");
        return java.nio.file.Files.readString(file.toPath(), java.nio.charset.StandardCharsets.UTF_8);
    }

    private static Set<String> editableParameterNames(Element mojoElement, String goal) {
        Set<String> names = new LinkedHashSet<>();
        Element parameters = firstChild(mojoElement, "parameters");
        assertNotNull(parameters, "No <parameters> element in the descriptor for goal " + goal);
        for (Element parameter : childElements(parameters)) {
            Element editable = firstChild(parameter, "editable");
            if (editable != null && "true".equals(editable.getTextContent().trim())) {
                names.add(text(firstChild(parameter, "name")));
            }
        }
        return names;
    }

    private static Element findMojo(Document descriptor, String goal) {
        NodeList mojos = descriptor.getElementsByTagName("mojo");
        for (int i = 0; i < mojos.getLength(); i++) {
            Element candidate = (Element) mojos.item(i);
            if (goal.equals(text(firstChild(candidate, "goal")))) {
                return candidate;
            }
        }
        fail("No <mojo> with goal '" + goal + "' in META-INF/maven/plugin.xml");
        return null;
    }

    private static String text(Element element) {
        return element == null ? null : element.getTextContent().trim();
    }

    private static Element firstChild(Element parent, String name) {
        for (Element element : childElements(parent)) {
            if (name.equals(element.getTagName())) {
                return element;
            }
        }
        return null;
    }

    private static List<Element> childElements(Element parent) {
        List<Element> elements = new ArrayList<>();
        NodeList children = parent.getChildNodes();
        for (int i = 0; i < children.getLength(); i++) {
            Node child = children.item(i);
            if (child.getNodeType() == Node.ELEMENT_NODE) {
                elements.add((Element) child);
            }
        }
        return elements;
    }
}
